CREATE TABLE SPRING_SESSION (
 PRIMARY_ID CHAR(36) NOT NULL PRIMARY KEY, SESSION_ID CHAR(36) NOT NULL,
 CREATION_TIME BIGINT NOT NULL, LAST_ACCESS_TIME BIGINT NOT NULL, MAX_INACTIVE_INTERVAL INT NOT NULL,
 EXPIRY_TIME BIGINT NOT NULL, PRINCIPAL_NAME VARCHAR(100));
CREATE UNIQUE INDEX SPRING_SESSION_IX1 ON SPRING_SESSION (SESSION_ID);
CREATE INDEX SPRING_SESSION_IX2 ON SPRING_SESSION (EXPIRY_TIME);
CREATE INDEX SPRING_SESSION_IX3 ON SPRING_SESSION (PRINCIPAL_NAME);
CREATE TABLE SPRING_SESSION_ATTRIBUTES (
 SESSION_PRIMARY_ID CHAR(36) NOT NULL REFERENCES SPRING_SESSION(PRIMARY_ID) ON DELETE CASCADE,
 ATTRIBUTE_NAME VARCHAR(200) NOT NULL, ATTRIBUTE_BYTES BYTEA NOT NULL,
 PRIMARY KEY(SESSION_PRIMARY_ID, ATTRIBUTE_NAME));
CREATE TABLE auth_audit (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 method VARCHAR(16) NOT NULL CHECK(method IN ('ldap','kerberos')),
 outcome VARCHAR(16) NOT NULL CHECK(outcome IN ('success','failure','throttled')),
 subject VARCHAR(64) NOT NULL, source_address VARCHAR(64) NOT NULL, trace_id VARCHAR(32) NOT NULL);
CREATE INDEX auth_audit_time ON auth_audit(occurred_at);

CREATE TABLE kerberos_replay (
 token_hash CHAR(64) NOT NULL PRIMARY KEY,
 accepted_at TIMESTAMPTZ NOT NULL DEFAULT now());
CREATE INDEX kerberos_replay_time ON kerberos_replay(accepted_at);
